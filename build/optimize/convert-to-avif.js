const crypto = require('crypto');
const fs = require('fs-extra');
const path = require('path');
const sharp = require('sharp');

/**
 * AVIF encoder settings. They are part of every fingerprint, so changing them
 * regenerates every AVIF on the next build.
 */
const AVIF_OPTIONS = { quality: 80 };

/**
 * Generated AVIFs live in `src/images/` next to their source image and are
 * committed. AVIF encoders produce different bytes on macOS and Linux, so
 * encoding once and copying afterwards keeps every build's output identical.
 *
 * `avif-manifest.json` maps each generated AVIF (relative to `src/images/`)
 * to its source and a fingerprint of that source. A missing AVIF, a changed
 * source, or changed settings triggers a re-encode into `src/`.
 */
const MANIFEST_NAME = 'avif-manifest.json';

function imagesDir(dir) {
  return path.join(dir.src, 'images');
}

function manifestPath(dir) {
  return path.join(imagesDir(dir), MANIFEST_NAME);
}

function relativeToImages(file, dir) {
  return path.relative(imagesDir(dir), file).split(path.sep).join('/');
}

function withExtension(file, extension) {
  return `${file.substring(0, file.lastIndexOf('.'))}${extension}`;
}

// Read and written synchronously so concurrent conversions can't lose updates.
function readManifest(dir) {
  const file = manifestPath(dir);
  return fs.existsSync(file) ? fs.readJsonSync(file) : {};
}

function writeManifest(dir, manifest) {
  const sorted = {};
  Object.keys(manifest).sort().forEach((key) => { sorted[key] = manifest[key]; });
  fs.writeFileSync(manifestPath(dir), `${JSON.stringify(sorted, null, 2)}\n`);
}

/**
 * Fingerprints a source image together with the encoder settings.
 *
 * @param {string} sourceImage - Absolute path to the source image.
 * @returns {string} 16 hex characters of a SHA-256 digest.
 */
function fingerprint(sourceImage) {
  return crypto.createHash('sha256')
    .update(JSON.stringify(AVIF_OPTIONS))
    .update(fs.readFileSync(sourceImage))
    .digest('hex')
    .substring(0, 16);
}

/**
 * Whether an AVIF in `src/images/` was generated by the build (and so is
 * owned by its source image) rather than supplied as a source itself.
 *
 * @param {string} avifPath - Absolute path to an AVIF in `src/images/`.
 * @param {{ dir: { src: string } }} options
 * @returns {boolean}
 */
function isGeneratedAvif(avifPath, { dir }) {
  const manifest = readManifest(dir);
  return Object.prototype.hasOwnProperty.call(manifest, relativeToImages(avifPath, dir));
}

/**
 * Deletes the generated AVIF of a removed source image and its manifest entry.
 *
 * @param {string} sourceImage - Absolute path to the removed source image.
 * @param {{ dir: { src: string } }} options
 */
function removeGeneratedAvif(sourceImage, { dir }) {
  const avifPath = withExtension(sourceImage, '.avif');
  const key = relativeToImages(avifPath, dir);
  const manifest = readManifest(dir);
  if (!manifest[key] || manifest[key].source !== relativeToImages(sourceImage, dir)) return;
  delete manifest[key];
  writeManifest(dir, manifest);
  fs.removeSync(avifPath);
}

/**
 * Writes a raster image's AVIF sibling to the output directory.
 *
 * Copies the committed AVIF from `src/images/` when it is current, and
 * encodes a new one into `src/images/` first when it is missing or stale.
 *
 * @param {string} sourceImage - Absolute path to the source image.
 * @param {{ dir: { src: string, package: string } }} options
 * @returns {Promise<void>}
 */
async function convertToAvif(sourceImage, { dir }) {
  const sourceAvif = withExtension(sourceImage, '.avif');
  const key = relativeToImages(sourceAvif, dir);
  const source = relativeToImages(sourceImage, dir);
  const sha256 = fingerprint(sourceImage);
  const entry = readManifest(dir)[key];

  const isCurrent = entry && entry.source === source && entry.sha256 === sha256
    && fs.existsSync(sourceAvif);
  if (!isCurrent) {
    await sharp(sourceImage).avif(AVIF_OPTIONS).toFile(sourceAvif);
    const manifest = readManifest(dir);
    manifest[key] = { source, sha256 };
    writeManifest(dir, manifest);
  }

  const destination = sourceAvif.replace(dir.src, dir.package);
  await fs.copyFile(sourceAvif, destination);
}

module.exports = convertToAvif;
module.exports.MANIFEST_NAME = MANIFEST_NAME;
module.exports.fingerprint = fingerprint;
module.exports.isGeneratedAvif = isGeneratedAvif;
module.exports.removeGeneratedAvif = removeGeneratedAvif;
